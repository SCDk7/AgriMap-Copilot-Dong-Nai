const localeNames = { vi: "Tiếng Việt", en: "English", zh: "中文", ko: "한국어", ja: "日本語" };
const localeCodes = Object.keys(localeMessages);
let activeLocale = localStorage.getItem("ocop-language");
if (!localeCodes.includes(activeLocale)) activeLocale = "vi";

function translate(key) {
  return localeMessages[activeLocale][key] || localeMessages.vi[key] || key;
}

function applyLocale(code) {
  if (!localeCodes.includes(code)) return;
  activeLocale = code;
  localStorage.setItem("ocop-language", code);
  document.documentElement.lang = code;
  document.title = translate(document.body.classList.contains("landing-page") ? "home.documentTitle" : "shop.documentTitle");

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = translate(element.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    element.placeholder = translate(element.dataset.i18nPlaceholder);
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    element.setAttribute("aria-label", translate(element.dataset.i18nAria));
  });
  document.querySelectorAll(".locale-code").forEach((element) => {
    element.textContent = code.toUpperCase();
  });
  document.querySelectorAll("[data-locale]").forEach((element) => {
    const selected = element.dataset.locale === code;
    element.setAttribute("aria-checked", String(selected));
  });
  window.dispatchEvent(new CustomEvent("ocop:languagechange", { detail: { locale: code } }));
}

document.querySelectorAll(".locale-picker").forEach((picker) => {
  const trigger = picker.querySelector(".locale-trigger");
  const menu = picker.querySelector(".locale-menu");
  menu.hidden = true;
  trigger.addEventListener("click", () => {
    const open = menu.hidden;
    menu.hidden = !open;
    trigger.setAttribute("aria-expanded", String(open));
  });
  menu.addEventListener("click", (event) => {
    const option = event.target.closest("[data-locale]");
    if (!option) return;
    applyLocale(option.dataset.locale);
    menu.hidden = true;
    trigger.setAttribute("aria-expanded", "false");
    trigger.focus();
  });
});

document.addEventListener("click", (event) => {
  document.querySelectorAll(".locale-picker").forEach((picker) => {
    if (picker.contains(event.target)) return;
    const menu = picker.querySelector(".locale-menu");
    menu.hidden = true;
    picker.querySelector(".locale-trigger").setAttribute("aria-expanded", "false");
  });
});

document.addEventListener("keydown", (event) => {
  if (event.key !== "Escape") return;
  document.querySelectorAll(".locale-picker").forEach((picker) => {
    const menu = picker.querySelector(".locale-menu");
    if (menu.hidden) return;
    menu.hidden = true;
    picker.querySelector(".locale-trigger").setAttribute("aria-expanded", "false");
    picker.querySelector(".locale-trigger").focus();
  });
});

window.ocopLocale = {
  t: translate,
  get current() { return activeLocale; },
  set: applyLocale
};

applyLocale(activeLocale);
